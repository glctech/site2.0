  /* ── DETECTAR IDIOMA ─────────────────────────────────────────────────────── */

  function detectLang() {
    // 1. Preferência salva pelo usuário
    var saved = localStorage.getItem('glctech_lang');
    if (saved && translations[saved]) return saved;

    // 2. navigator.languages (lista de preferências do navegador)
    var langs = navigator.languages || [navigator.language || navigator.userLanguage || 'pt'];
    for (var i = 0; i < langs.length; i++) {
      var loc = (langs[i] || '').toLowerCase();
      if (localeMap[loc])        return localeMap[loc];
      var base = loc.split('-')[0];
      if (localeMap[base])       return localeMap[base];
    }
    return 'pt'; // padrão
  }

  /* ── APLICAR TRADUÇÃO ────────────────────────────────────────────────────── */

  function t(key, lang) {
    var dict = translations[lang] || translations['pt'];
    return dict[key] !== undefined ? dict[key] : (translations['pt'][key] || key);
  }

  function applyLang(lang) {
    var dict = translations[lang] || translations['pt'];

    // Atualiza <html lang="...">
    document.documentElement.lang = dict['page.lang'] || lang;

    // Traduz o <title> usando a chave própria da página (data-i18n do <title>).
    // Páginas sem data-i18n no <title> mantêm o texto estático do HTML —
    // nunca usam a chave 'page.title' de outra página como fallback.
    var titleEl = document.querySelector('title[data-i18n]');
    if (titleEl) {
      var titleKey = titleEl.getAttribute('data-i18n');
      if (dict[titleKey] !== undefined) {
        document.title = dict[titleKey];
      } else if (translations['pt'][titleKey] !== undefined) {
        document.title = translations['pt'][titleKey];
      }
    }

    // Traduz todos os elementos com data-i18n
    var els = document.querySelectorAll('[data-i18n],[data-i18n-html],[data-i18n-attr]');
    /* Use the correct attribute name as the key */
    function getKey(el) { return el.getAttribute('data-i18n') || el.getAttribute('data-i18n-html') || el.getAttribute('data-i18n-attr'); }
    for (var i = 0; i < els.length; i++) {
      var el  = els[i];
      var key = getKey(el);
      var val = t(key, lang);

      if (el.hasAttribute('data-i18n-attr')) {
        // Traduzir atributo (placeholder, aria-label, etc.)
        var attr = el.getAttribute('data-i18n-attr');
        el.setAttribute(attr, val);
      } else if (el.hasAttribute('data-i18n-html')) {
        // Traduzir innerHTML
        el.innerHTML = val;
      } else {
        // Traduzir textContent (padrão)
        el.textContent = val;
      }
    }

    // Atualiza variáveis JS para validação do formulário
    window._i18n_errors = {
      nome:    t('form.err.nome',  lang),
      email:   t('form.err.email', lang),
      msg:     t('form.err.msg',   lang),
      send:    t('form.err.send',  lang),
    };

    // Atualizar seletor de idioma customizado
    if (window._glcSelectLang) {
      window._glcSelectLang(lang);
    }

    // Salva preferência
    localStorage.setItem('glctech_lang', lang);
    window._currentLang = lang;
  }

